#!/usr/bin/env bash
# Set up a Keycloak realm for trying SSO with `examples/auth` (docs/SSO_TESTING_KEYCLOAK.md).
#
# Creates, through Keycloak's admin REST API:
#   - a realm (default `rl-sso-test`) for testing only;
#   - a confidential OIDC client `relativelylight-demo` whose redirect URL is the example's callback;
#   - a `groups` claim in its tokens (group names, no path);
#   - a group `rl-admins`, which the example maps to its local admin group;
#   - two users with generated passwords: `sso-admin` (in `rl-admins`) and `sso-user`.
# and writes the example's settings, client secret and the users' passwords to an env file.
#
# Inputs (environment):
#   KC_URL             Keycloak's base URL, e.g. http://localhost:8080            (required)
#   KC_ADMIN           an admin of the `master` realm                             (required)
#   KC_ADMIN_PASSWORD  its password                                               (required)
#   REALM              the test realm to create             (default rl-sso-test)
#   APP_URL            where the example runs               (default http://localhost:3000)
#   OUT                the env file to write                (default examples/auth/keycloak.local.env)
#   RESET=1            delete and recreate REALM if it already exists (it is a test realm)
#
# Needs: bash, curl, python3.
set -euo pipefail

: "${KC_URL:?set KC_URL, e.g. http://localhost:8080}"
: "${KC_ADMIN:?set KC_ADMIN}"
: "${KC_ADMIN_PASSWORD:?set KC_ADMIN_PASSWORD}"
REALM="${REALM:-rl-sso-test}"
APP_URL="${APP_URL:-http://localhost:3000}"
OUT="${OUT:-$(dirname "$0")/keycloak.local.env}"
CLIENT_ID="relativelylight-demo"
KC_URL="${KC_URL%/}"

json() { python3 -I -c "import json,sys; d=json.load(sys.stdin); print($1)"; }
password() { python3 -I -c "import secrets; print(secrets.token_urlsafe(18))"; }

TOKEN=$(curl -sf -X POST "$KC_URL/realms/master/protocol/openid-connect/token" \
  -d grant_type=password -d client_id=admin-cli -d username="$KC_ADMIN" \
  --data-urlencode "password=$KC_ADMIN_PASSWORD" | json "d['access_token']")
api() { # method path [json body]
  local method=$1 path=$2
  shift 2
  curl -sf -X "$method" "$KC_URL/admin/realms$path" -H "Authorization: Bearer $TOKEN" \
    -H "Content-Type: application/json" "$@"
}

if api GET "/$REALM" -o /dev/null; then
  if [ "${RESET:-}" = "1" ]; then
    echo "deleting the existing realm $REALM (RESET=1)"
    api DELETE "/$REALM"
  else
    echo "realm $REALM already exists; RESET=1 recreates it" >&2
    exit 1
  fi
fi

echo "creating realm $REALM"
api POST "" -d "{\"realm\": \"$REALM\", \"enabled\": true}"

echo "creating client $CLIENT_ID (redirect $APP_URL/sso/keycloak/callback)"
api POST "/$REALM/clients" -d "{
  \"clientId\": \"$CLIENT_ID\",
  \"name\": \"relativelylight auth example\",
  \"protocol\": \"openid-connect\",
  \"publicClient\": false,
  \"standardFlowEnabled\": true,
  \"directAccessGrantsEnabled\": false,
  \"redirectUris\": [\"$APP_URL/sso/keycloak/callback\"],
  \"protocolMappers\": [{
    \"name\": \"groups\",
    \"protocol\": \"openid-connect\",
    \"protocolMapper\": \"oidc-group-membership-mapper\",
    \"config\": {\"claim.name\": \"groups\", \"full.path\": \"false\",
                 \"id.token.claim\": \"true\", \"access.token.claim\": \"true\", \"userinfo.token.claim\": \"true\"}
  }]
}"
CLIENT_UUID=$(api GET "/$REALM/clients?clientId=$CLIENT_ID" | json "d[0]['id']")
CLIENT_SECRET=$(api GET "/$REALM/clients/$CLIENT_UUID/client-secret" | json "d['value']")

echo "creating group rl-admins"
api POST "/$REALM/groups" -d '{"name": "rl-admins"}'
GROUP_ID=$(api GET "/$REALM/groups?search=rl-admins" | json "[g['id'] for g in d if g['name']=='rl-admins'][0]")

make_user() { # username first last password [group-id]
  local user=$1 first=$2 last=$3 pw=$4 group=${5:-}
  echo "creating user $user"
  api POST "/$REALM/users" -d "{
    \"username\": \"$user\", \"enabled\": true, \"emailVerified\": true,
    \"email\": \"$user@example.test\", \"firstName\": \"$first\", \"lastName\": \"$last\",
    \"credentials\": [{\"type\": \"password\", \"value\": \"$pw\", \"temporary\": false}]
  }"
  if [ -n "$group" ]; then
    local id
    id=$(api GET "/$REALM/users?username=$user&exact=true" | json "d[0]['id']")
    api PUT "/$REALM/users/$id/groups/$group"
  fi
}
ADMIN_PW=$(password)
USER_PW=$(password)
make_user sso-admin Sso Admin "$ADMIN_PW" "$GROUP_ID"
make_user sso-user Sso User "$USER_PW"

umask 077
cat > "$OUT" <<EOF
# Generated by examples/auth/keycloak-setup.sh for realm $REALM at $KC_URL. Holds a client secret
# and test passwords: keep it out of git (*.local.env is ignored).
SSO_BASE_URL=$APP_URL
SSO_OIDC_ISSUER=$KC_URL/realms/$REALM
SSO_OIDC_CLIENT_ID=$CLIENT_ID
SSO_OIDC_CLIENT_SECRET=$CLIENT_SECRET
SSO_OIDC_KEY=keycloak
SSO_OIDC_LABEL=Keycloak
SSO_OIDC_ADMIN_GROUP=rl-admins
# Uncomment for strict re-authentication (docs/AUTH.md §5h): a confirmation needs a sign-in at most
# this many seconds old, and Keycloak asks for the password again when the last one is older.
#SSO_OIDC_REAUTH_MAX_AGE=60

# Test users in Keycloak (sign in with these at the Keycloak page):
#   sso-admin  $ADMIN_PW   (group rl-admins → the example's admin group)
#   sso-user   $USER_PW
EOF
echo "wrote $OUT"
